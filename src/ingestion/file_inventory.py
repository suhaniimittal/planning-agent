"""Stage 0 of ingestion: what every file in a repo IS, before any parsing.

Every file gets a FileRecord — and so a File node — whether or not a parser
understands it, and whether or not parsing it later fails. Before this, a
file reached the graph only if parsing succeeded or it had a known
extension, and an audit of 13 services found 12 files with no node at all
(11 generated GraphQL clients in reports-api, whose parse blew Python's
recursion limit, and one 20KB union type in ui).

The record also carries the file's full text, so the graph holds every
line of every text file: 933 Liquibase .sql files, every .yaml, .json and
Jenkinsfile were nodes with a name and nothing else.

What is STORED and what is SEARCHED are decided separately. Generated code,
lockfiles and minified bundles are stored — a coding agent may still need
to read or edit them — but `searchable` is False, so they are never
embedded and never crowd real code out of a search.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import PurePosixPath

from .test_paths import is_test_path

# A file's text is stored up to this many characters; beyond it the text is
# cut and `truncated` is set. Set far above real source files (the largest
# hand-written file found across 13 services is ~200KB) so only generated
# blobs ever reach it.
MAX_STORED_SOURCE_CHARS = 1_000_000

# Above this, a text file is stored but not embedded: no hand-written file
# is this large, and embedding a 300KB data dump buys noise, not search.
MAX_SEARCHABLE_CHARS = 300_000

# Average characters per line above which a file is treated as minified.
_MINIFIED_AVG_LINE_CHARS = 400

# How much of a file is sniffed for a null byte (binary) or a generated-code
# banner. Banners sit in the first few lines; 8KB covers any licence header
# in front of one.
_SNIFF_BYTES = 8192

_GENERATED_BANNER = re.compile(
    r"@generated|do not edit|do not modify|auto-?generated|automatically generated|"
    r"code generated by|generated by apollo|this file was generated",
    re.IGNORECASE,
)
_GENERATED_DIR_PARTS = {"generated", "__generated__", "generated-sources", "gen-src"}
_GENERATED_NAME = re.compile(r"\.(generated|gen)\.\w+$|_pb2\.py$|\.pb\.go$", re.IGNORECASE)

# Present in every repo, read by nobody looking for behaviour.
_LOCKFILES = {
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "uv.lock",
    "Pipfile.lock",
    "Cargo.lock",
    "Gemfile.lock",
    "composer.lock",
    "gradlew",
    "gradlew.bat",
}

_SCHEMA_EXTENSIONS = {".graphqls", ".graphql", ".gql", ".avdl", ".avsc", ".proto", ".xsd", ".bpmn"}
_CONFIG_EXTENSIONS = {
    ".yml",
    ".yaml",
    ".properties",
    ".json",
    ".toml",
    ".ini",
    ".conf",
    ".cfg",
    ".env",
    ".xml",
    ".template",
}
_DOC_EXTENSIONS = {".md", ".txt", ".rst", ".adoc"}
_BUILD_NAMES = {
    "Dockerfile",
    "Jenkinsfile",
    "Makefile",
    "build.gradle",
    "build.gradle.kts",
    "settings.gradle",
    "settings.gradle.kts",
    "pom.xml",
    "package.json",
    "tsconfig.json",
    "pyproject.toml",
    "setup.py",
    "setup.cfg",
}
_BUILD_EXTENSIONS = {".gradle", ".kts", ".sh", ".bash", ".dockerfile", ".ci-cd"}
_MIGRATION_DIR_PARTS = {"liquibase", "migration", "migrations", "flyway", "changelog", "changelogs"}


@dataclass
class FileRecord:
    """Everything known about one file before parsing.

    `kind`: source | test | migration | schema | config | build | doc |
    data | generated | binary. `parse_status` starts as "unsupported" for a
    file no parser reads, "pending" for one that will be parsed, and is
    moved to "ok" / "failed" / "oversized" by the parser."""

    file_path: str
    kind: str
    language: str
    size: int
    source: str | None
    line_count: int
    truncated: bool
    searchable: bool
    generated: bool
    parse_status: str = "unsupported"
    parse_error: str | None = None


def is_binary(head: bytes) -> bool:
    return b"\x00" in head[:_SNIFF_BYTES]


def is_generated(file_path: str, text_head: str) -> bool:
    path = PurePosixPath(file_path)
    if any(part.lower() in _GENERATED_DIR_PARTS for part in path.parts[:-1]):
        return True
    if _GENERATED_NAME.search(path.name):
        return True
    # Only the banner area counts: a hand-written file may say "do not edit
    # this list by hand" in a comment halfway down.
    head_lines = "\n".join(text_head.splitlines()[:15])
    return bool(_GENERATED_BANNER.search(head_lines))


def is_minified(text: str) -> bool:
    lines = text.count("\n") + 1
    return len(text) > 5000 and len(text) / lines > _MINIFIED_AVG_LINE_CHARS


def classify(file_path: str, generated: bool, binary: bool) -> str:
    if binary:
        return "binary"
    if generated:
        return "generated"
    path = PurePosixPath(file_path)
    suffix = path.suffix.lower()
    parts = {p.lower() for p in path.parts[:-1]}
    if is_test_path(file_path) or suffix == ".feature":
        return "test"
    if suffix == ".sql" or (parts & _MIGRATION_DIR_PARTS and suffix in {".xml", ".yaml", ".yml"}):
        return "migration"
    if suffix in _SCHEMA_EXTENSIONS:
        return "schema"
    if path.name in _BUILD_NAMES or path.name in _LOCKFILES or suffix in _BUILD_EXTENSIONS:
        return "build"
    if suffix in _CONFIG_EXTENSIONS or path.name.startswith(".env"):
        return "config"
    if suffix in _DOC_EXTENSIONS:
        return "doc"
    if suffix in {".csv", ".tsv"}:
        return "data"
    return "source"


def build_record(file_path: str, raw: bytes, language: str) -> FileRecord:
    """A FileRecord from a file's raw bytes. Never raises: undecodable
    bytes are replaced, and a binary file is recorded with no text."""
    if is_binary(raw):
        return FileRecord(
            file_path=file_path,
            kind="binary",
            language=language,
            size=len(raw),
            source=None,
            line_count=0,
            truncated=False,
            searchable=False,
            generated=False,
        )
    text = raw.decode("utf-8", errors="replace")
    generated = is_generated(file_path, text[:_SNIFF_BYTES])
    kind = classify(file_path, generated, binary=False)
    truncated = len(text) > MAX_STORED_SOURCE_CHARS
    searchable = not (
        generated
        or PurePosixPath(file_path).name in _LOCKFILES
        or len(text) > MAX_SEARCHABLE_CHARS
        or is_minified(text)
    )
    return FileRecord(
        file_path=file_path,
        kind=kind,
        language=language,
        size=len(raw),
        source=text[:MAX_STORED_SOURCE_CHARS],
        line_count=text.count("\n") + (0 if text.endswith("\n") or not text else 1),
        truncated=truncated,
        searchable=searchable,
        generated=generated,
    )


def file_row(record: FileRecord) -> dict:
    """The File-node properties this record owns. Other stages add theirs
    (imports, references, blob_sha) to the same row."""
    return {
        "file_path": record.file_path,
        "language": record.language,
        "kind": record.kind,
        "size": record.size,
        "line_count": record.line_count,
        "truncated": record.truncated,
        "searchable": record.searchable,
        "generated": record.generated,
        "parse_status": record.parse_status,
        "parse_error": record.parse_error,
        # "" rather than null for a binary file, so "no text" and "never
        # recorded" stay distinguishable to a reader.
        "source": record.source or "",
    }
